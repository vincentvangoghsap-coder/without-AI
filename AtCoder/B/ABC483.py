'''
1からNまでの番号が書かれた（表裏の区別できる）N枚のカードがあり、最初、上から1,2,…,N の順ですべて表向きで積まれています。
高橋君はこの山にQ回の操作を行います。
i回目（1≤i≤Q）の操作では以下の操作を行います。
上からK_i​枚のカードをひとまとめにして裏返し、元の位置に戻す。
これにより、上から K_i枚のカードの順序が上下逆になり、それぞれのカードの表裏も反転する。
すべての操作を終えた後のカードの順序と表裏を求めてください。
具体的には、i=1,2,…,N について、上からi枚目に置かれているカードに書かれている番号が 
X_iのとき、そのカードが表向きで積まれている時X_iを、裏向きなら−X_i​を出力してください。

制約
1≤N,Q≤100
1≤K_i≤N
入力はすべて整数
入力
入力は以下の形式で標準入力から与えられる。
N Q
K_1​ K_2 ⋯ K_Q 
出力
N行出力せよ。
i行目（1≤i≤N）には、Q回の操作の後で上からi枚目に置かれているカードに書かれている番号がX_iのとき、
そのカードが表向きで積まれている時X_iを、裏向きなら−X_iを出力せよ。
'''
N, Q = input().split()
N = int(N)
Q = int(Q)
b = []
for i in range(N):
  b.append(i + 1)
a = list(map(int, input().split()))
for i in range (Q):
  if a[i] % 2 == 0 and a[i] > 1:
    for k in range (a[i] // 2):
      b[0 + k], b[a[i] - k - 1] = -b[a[i] - k - 1], -b[0 + k]
  elif a[i] > 1:
    for k in range(a[i] // 2):
      b[0 + k], b[a[i] - k - 1] = -b[a[i] - k - 1], -b[0 + k]
    b[a[i] // 2] = -b[a[i] // 2]
  elif a[i] == 1:
    b[0] = -b[0]
for i in range(len(b)):
  print(b[i])
